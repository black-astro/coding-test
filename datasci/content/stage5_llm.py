            "            행 하나가 토큰 하나의 의미 벡터다.\n"
            "  X = embedding[token_ids]\n"
            "         → 팬시 인덱싱으로 여러 토큰의 벡터를 한 번에 꺼낸다.\n"
            "            (토큰 수, d_model) 모양이 된다.\n"
            "  Q, K, V = X @ Wq, X @ Wk, X @ Wv\n"
            "         → 같은 입력에서 세 가지 역할의 벡터를 만든다.\n"
            "            '셀프' 어텐션인 이유가 이것이다. Q·K·V 가 모두 자기 자신에서 나온다.\n"
            "  scores = Q @ K.T / np.sqrt(d_k)\n"
            "         → 모든 단어 쌍의 관련도. (n, n) 정사각 행렬이 된다.\n"
            "  mask 적용\n"
            "         → GPT 같은 생성 모델은 뒤쪽 단어를 미리 보면 안 된다(컨닝 방지).\n"
            "            위쪽 삼각형에 -무한대를 채우면 softmax 후 0 이 되어 차단된다.\n"
            "            이를 causal mask 라 한다.\n"
            "  weights @ V\n"
            "         → 가중 평균. 각 단어가 문맥을 반영한 새 벡터를 갖게 된다.\n"
