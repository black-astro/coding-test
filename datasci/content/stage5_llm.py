            "  √d 로 나눠 적당한 크기로 유지하는 것이다. 그래서 'scaled' dot-product attention 이다.\n"
            "\n"
            "[코드 분석]\n"
            "  embedding = rng.normal(0, 1, (vocab_size, d_model))\n"
