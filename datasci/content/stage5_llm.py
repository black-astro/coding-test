            "\n"
            "  계산 순서:\n"
            "    1) score = Q @ K.T          질문과 색인을 대조 → 관련도 점수\n"
            "    2) score / √d               차원 수의 제곱근으로 나눈다 (스케일링)\n"
            "    3) weight = softmax(score)  점수를 합이 1인 가중치로\n"
            "    4) output = weight @ V      가중치대로 내용을 섞는다\n"
            "\n"
            "  이 네 줄이 트랜스포머의 핵심이다. 'Attention Is All You Need' 의 그 수식이다.\n"
            "\n"
            "[왜 √d 로 나누는가]\n"
            "  차원이 크면 내적 값이 커진다. 값이 크면 softmax 가 극단적으로 쏠려\n"
