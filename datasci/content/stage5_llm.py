            "\n"
            "비슷한 의미의 단어는 벡터 공간에서 가까이 놓인다.\n"
            "임베딩 값은 사람이 정하는 게 아니라 학습으로 얻는다.\n"
            "\n"
            "[셀프 어텐션 — Q, K, V]\n"
            "도서관에서 자료를 찾는 과정에 비유하면 이해하기 쉽다.\n"
            "\n"
            "  Query (질문)  : 내가 찾는 것            '그것'이 뭘 가리키지?\n"
            "  Key   (색인)  : 각 자료의 검색용 표지    각 단어의 '나는 이런 단어다'\n"
